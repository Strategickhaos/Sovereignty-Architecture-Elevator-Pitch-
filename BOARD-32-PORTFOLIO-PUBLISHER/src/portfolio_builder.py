# ── Main builder ──────────────────────────────────────────────────────────────

def build_all(only: str = "all"):
    OUT_CASES.mkdir(parents=True, exist_ok=True)
    OUT_RESUME.mkdir(parents=True, exist_ok=True)
    OUT_RPT.mkdir(parents=True, exist_ok=True)

    inventions = harvest_inventions()
    eru_cases  = harvest_eru_cases()
    certs      = harvest_certs()
    antibodies = harvest_antibodies()
    boards     = [str(d.name) for d in REPO_ROOT.iterdir()
                  if d.is_dir() and d.name.startswith("BOARD-")]

    case_files: list[Path] = []

    if only in ("all", "case-studies"):
        # Invention case studies
        for seed in inventions:
            slug = seed.get("seed_id", seed.get("title", "unknown")).replace(" ", "_").replace("/", "-")
            out  = OUT_CASES / f"{slug}.md"
            out.write_text(render_invention_case_study(seed))
            case_files.append(out)
            print(f"  case-study → {out.relative_to(REPO_ROOT)}")

        # ERU case studies
        seen_slugs: dict[str, int] = {}
        for case in eru_cases[:6]:  # top 6
            base_slug = (case.get("case_id") or case.get("title") or "eru_case").replace(" ", "_").replace("/", "-")
            seen_slugs[base_slug] = seen_slugs.get(base_slug, 0) + 1
            slug = base_slug if seen_slugs[base_slug] == 1 else f"{base_slug}_{seen_slugs[base_slug]}"
            out  = OUT_CASES / f"{slug}.md"
            out.write_text(render_gke_case_study(case))
            case_files.append(out)
            print(f"  case-study → {out.relative_to(REPO_ROOT)}")

    resume_files: list[Path] = []
    if only in ("all", "resume"):
        out = OUT_RESUME / "distinguished_engineer_bullets.md"
        out.write_text(render_resume_bullets(inventions, certs, antibodies, boards))
        resume_files.append(out)
        print(f"  resume    → {out.relative_to(REPO_ROOT)}")

    if only in ("all", "index"):
        index_out = BOARD / "portfolio_index.md"
        index_out.write_text(render_index(case_files, resume_files, inventions, antibodies))
        print(f"  index     → {index_out.relative_to(REPO_ROOT)}")

    # Inventory report
    inventory = {
        "generated": NOW,
        "inventions": len(inventions),
        "eru_cases": len(eru_cases),
        "certs": len(certs),
        "antibodies": len(antibodies),
        "boards": len(boards),
        "case_studies_rendered": len(case_files),
        "resume_bullets_rendered": len(resume_files),
    }
    (OUT_RPT / "portfolio_inventory.yaml").write_text(yaml.dump(inventory, sort_keys=False))
    print(f"\n  Portfolio built — {len(case_files)} case studies, {len(resume_files)} resume docs")


def main():
    import argparse
    ap = argparse.ArgumentParser()
    ap.add_argument("--build",        action="store_true")
    ap.add_argument("--case-studies", action="store_true")
    ap.add_argument("--resume",       action="store_true")
    ap.add_argument("--index",        action="store_true")
    ap.add_argument("--list",         action="store_true")
    args = ap.parse_args()

    if args.list:
        print(f"\n  Inventions  : {len(harvest_inventions())}")
        print(f"  ERU cases   : {len(harvest_eru_cases())}")
        print(f"  Certs       : {len(harvest_certs())}")
        print(f"  Antibodies  : {len(harvest_antibodies())}")
        return

    if args.build or not any(vars(args).values()):
        build_all("all")
    elif args.case_studies:
        build_all("case-studies")
    elif args.resume:
        build_all("resume")
    elif args.index:
        build_all("index")


if __name__ == "__main__":
    main()
