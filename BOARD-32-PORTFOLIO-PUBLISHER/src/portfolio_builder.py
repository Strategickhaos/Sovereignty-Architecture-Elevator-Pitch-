#!/usr/bin/env python3
"""
BOARD-32 Portfolio Publisher

Harvests ERU artifacts from every board and renders:
  - case-studies/*.md          one per major proof
  - resume-bullets/*.md        STAR-format bullets
  - portfolio_index.md         master landing page

Usage:
  python portfolio_builder.py --build          full build
  python portfolio_builder.py --case-studies   only case studies
  python portfolio_builder.py --resume         only resume bullets
  python portfolio_builder.py --index          only index
  python portfolio_builder.py --list           list all source artifacts
"""

from __future__ import annotations
import json, yaml, sys, datetime
from pathlib import Path
from typing import Any

REPO_ROOT = Path(__file__).resolve().parents[2]
BOARD     = REPO_ROOT / "BOARD-32-PORTFOLIO-PUBLISHER"
OUT_CASES = BOARD / "case-studies"
OUT_RESUME= BOARD / "resume-bullets"
OUT_RPT   = BOARD / "reports"

NOW = datetime.date.today().isoformat()


# ── Source harvesters ─────────────────────────────────────────────────────────

def _load_yaml(p: Path) -> dict:
    try:
        return yaml.safe_load(p.read_text()) or {}
    except Exception:
        return {}

def _load_json(p: Path) -> Any:
    try:
        return json.loads(p.read_text())
    except Exception:
        return {}


def harvest_inventions() -> list[dict]:
    seeds_dir = REPO_ROOT / "MISSING-LINKS" / "seeds"
    return [_load_yaml(f) for f in sorted(seeds_dir.glob("*.yaml"))] if seeds_dir.exists() else []


def harvest_closed_cases() -> list[dict]:
    dirs = [
        REPO_ROOT / "MISSING-LINKS" / "cases" / "closed",
        REPO_ROOT / "BOARD-26-REMEDIATION-ENGINE" / "cases" / "closed",
    ]
    cases = []
    for d in dirs:
        if d.exists():
            cases += [_load_yaml(f) for f in sorted(d.glob("*.yaml"))]
    return cases


def harvest_eru_cases() -> list[dict]:
    sources = [
        REPO_ROOT / "BOARD-21-PHYSICS-FLEET" / "reports",
        REPO_ROOT / "BOARD-24-GCP-MASTERY" / "eru",
        REPO_ROOT / "BOARD-31-CELLPHONE-MOBIUS-LAB" / "reports",
    ]
    cases = []
    for d in sources:
        if d.exists():
            for f in sorted(d.glob("*.yaml")):
                data = _load_yaml(f)
                if data:
                    data["_source"] = str(f.relative_to(REPO_ROOT))
                    cases.append(data)
    return cases


def harvest_certs() -> list[dict]:
    cert_dir = REPO_ROOT / "BOARD-10-UNIVERSITY" / "certificates"
    return [_load_yaml(f) for f in sorted(cert_dir.glob("*.yaml"))] if cert_dir.exists() else []


def harvest_antibodies() -> list[dict]:
    ab_dir = REPO_ROOT / "BOARD-11-ANTIBODIES" / "antibodies"
    return [_load_yaml(f) for f in sorted(ab_dir.glob("*.yaml"))] if ab_dir.exists() else []


# ── Case study renderer ───────────────────────────────────────────────────────

def render_invention_case_study(seed: dict) -> str:
    title    = seed.get("title", "Unnamed Invention")
    inv      = seed.get("invention", {})
    inv_name = inv.get("name", title) if isinstance(inv, dict) else title
    law      = seed.get("law", "")
    boards   = (inv.get("boards_affected", []) if isinstance(inv, dict) else [])

    return f"""# Case Study: {inv_name}

**Date:** {seed.get('created', NOW)}
**District:** {seed.get('district', '?')}
**Boards:** {', '.join(boards) if boards else 'SAGCO-OS'}
**PMI Delta:** {seed.get('pmi_delta_estimate', '?')}

## ERU Loop

| Field | Value |
|-------|-------|
| **Expected** | {seed.get('expected', '?')} |
| **Actual** | {seed.get('actual', '?')} |
| **Variance** | {seed.get('variance', '?')} |

## Contradiction

{seed.get('contradiction', {}).get('description', seed.get('variance', '')) if isinstance(seed.get('contradiction'), dict) else ''}

**Invariant violated:** `{seed.get('invariant_violated', '?')}` — {law}

## Understanding

{seed.get('understanding', '').strip()}

## Invention

**{inv_name}**

{inv.get('description', '') if isinstance(inv, dict) else ''}

### Prototype Tasks

{chr(10).join(f'- {t}' for t in (inv.get('prototype_task', '').splitlines() if isinstance(inv, dict) else [])) or '- See seed file'}

## Verification

{chr(10).join(f'- {t}' for t in (seed.get('verification', {}).get('test_cases', []) if isinstance(seed.get('verification'), dict) else []))}

---
*Generated by BOARD-32-PORTFOLIO-PUBLISHER — SAGCO-OS*
"""


def render_gke_case_study(case: dict) -> str:
    title   = case.get("title", case.get("case_id", "ERU Case"))
    physics = case.get("physics_law", "")
    return f"""# Case Study: {title}

**Source:** `{case.get('_source', '?')}`
**Severity:** {case.get('severity', '?')}
**Physics Law:** {physics}

## ERU Loop

| Field | Value |
|-------|-------|
| **Expected** | {case.get('expected', '?')} |
| **Actual** | {case.get('actual', '?')} |
| **Variance** | {case.get('variance', '?')} |

## Understanding

{case.get('understanding', case.get('resolution', ''))}

## Proof

{case.get('proof', case.get('antibody', ''))}

---
*Generated by BOARD-32-PORTFOLIO-PUBLISHER — SAGCO-OS*
"""


